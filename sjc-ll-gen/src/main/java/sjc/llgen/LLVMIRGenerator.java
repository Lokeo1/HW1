    private void emitSideEffect(final Expression expression) {
      final ExpressionVisitor visitor = new ExpressionVisitor(true);
      expression.accept(visitor);
      visitor.requireHandled(expression);
    }

    private Value emitExpression(final Expression expression) {
      final ExpressionVisitor visitor = new ExpressionVisitor(false);
      expression.accept(visitor);
      visitor.requireHandled(expression);
      return visitor.value;
    }

    // Each invocation has its own result, so nested expression visits cannot
    // overwrite their parent's result.
